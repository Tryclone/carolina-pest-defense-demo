export default async (req) => {
  try {
    if (req.method !== "POST") {
      return new Response(
        JSON.stringify({ error: "Method not allowed" }),
        {
          status: 405,
          headers: {
            "Content-Type": "application/json"
          }
        }
      );
    }

    const data = await req.json();

    const botToken = process.env.TELEGRAM_BOT_TOKEN;
    const chatId = process.env.TELEGRAM_CHAT_ID;

    if (!botToken || !chatId) {
      console.error("Missing Telegram environment variables", {
        hasBotToken: !!botToken,
        hasChatId: !!chatId
      });

      return new Response(
        JSON.stringify({
          error: "Telegram environment variables are missing"
        }),
        {
          status: 500,
          headers: {
            "Content-Type": "application/json"
          }
        }
      );
    }

    const message =
      "🔔 NEW PEST CONTROL DEMO LEAD\n\n" +
      "👤 Name: " + (data.name || "N/A") + "\n" +
      "📞 Phone: " + (data.phone || "N/A") + "\n" +
      "📧 Email: " + (data.email || "N/A") + "\n" +
      "📍 Service Address: " + (data.address || "N/A") + "\n\n" +
      "🏠 Property Type: " + (data.propertyType || "N/A") + "\n" +
      "🐜 Pest Problem: " + (data.pestType || "N/A") + "\n" +
      "🛠️ Service Needed: " + (data.serviceNeeded || "N/A") + "\n" +
      "⏰ Urgency: " + (data.urgency || "N/A") + "\n" +
      "📝 Details: " + (data.details || "N/A") + "\n\n" +
      "🕒 Time: " + (data.timestamp || "N/A") + "\n\n" +
      "This is a demonstration lead generated by the Carolina Pest Defense demo.";

    const telegramResponse = await fetch(
      `https://api.telegram.org/bot${botToken}/sendMessage`,
      {
        method: "POST",
        headers: {
          "Content-Type": "application/json"
        },
        body: JSON.stringify({
          chat_id: chatId,
          text: message
        })
      }
    );

    const telegramResult = await telegramResponse.json();

    console.log("Telegram response:", {
      ok: telegramResponse.ok,
      status: telegramResponse.status,
      result: telegramResult
    });

    if (!telegramResponse.ok) {
      return new Response(
        JSON.stringify({
          error: "Failed to send Telegram message",
          details: telegramResult
        }),
        {
          status: 500,
          headers: {
            "Content-Type": "application/json"
          }
        }
      );
    }

    return new Response(
      JSON.stringify({
        success: true
      }),
      {
        status: 200,
        headers: {
          "Content-Type": "application/json"
        }
      }
    );

  } catch (error) {
    console.error("Function error:", error);

    return new Response(
      JSON.stringify({
        error: "Invalid request"
      }),
      {
        status: 400,
        headers: {
          "Content-Type": "application/json"
        }
      }
    );
  }
};